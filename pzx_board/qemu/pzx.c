// I2C register
#define PZX_I2C_CR 0x00
#define PZX_I2C_SR 0x04
#define PZX_I2C_ADDR 0x08
#define PZX_I2C_DR 0x0c
#define PZX_I2C_CLKDIV 0x10
#define PZX_I2C_MMIOSIZE 0x100

#define CR_EN (1u << 0)
#define CR_IEN (1u << 1)
#define CR_START (1u << 2)
#define CR_STOP (1u << 3)
#define CR_DIR (1u << 4) // 0-write 1-read
#define CR_NACK (1u << 5)

#define SR_BUSY (1u << 0)
#define SR_RXAK (1u << 1)
#define SR_IF (1u << 2)

struct PzxSysctlState {
    SysBusDevice parent;
    MemoryRegion iomem;
};

struct PzxI2CState {
    SysBusDevice parent;
    MemoryRegion iomem;
    qemu_irq irq;
    I2CBus *bus;

    uint32_t cr;
    uint32_t sr;
    uint32_t addr;
    uint32_t dr;
    uint32_t clkdiv;
};

