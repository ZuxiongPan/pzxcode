// self-defined devices realization

// sysctl device
static uint64_t pzx_sysctl_read(void *opaque, hwaddr addr, unsigned size)
{
    return 0xffffffffffffffff;
}

static void pzx_sysctl_write(void *opaque, hwaddr addr, uint64_t value, unsigned size)
{
    switch (addr)
    {
        case 0x0:
            // whatever value is written to this register, we just reset the system
            qemu_system_reset_request(SHUTDOWN_CAUSE_GUEST_RESET);
            break;
        default:
            break;
    }

    return ;
}

static const MemoryRegionOps pzx_sysctl_ops = {
    .read = pzx_sysctl_read,
    .write = pzx_sysctl_write,
    .endianness = DEVICE_LITTLE_ENDIAN,
};

static void pzx_sysctl_init(Object *obj)
{
    PzxSysctlState *state = PZX_SYSCTL(obj);
    SysBusDevice *dev = SYS_BUS_DEVICE(obj);

    memory_region_init_io(&state->iomem, obj, &pzx_sysctl_ops,
            state, "pzx-sysctl", 0x1000);
    sysbus_init_mmio(dev, &state->iomem);
}

// I2C Bus
static void pzx_i2c_update_irq(PzxI2CState *s)
{
    qemu_set_irq(s->irq, (s->cr & CR_EN) && (s->cr & CR_IEN) && (s->sr & SR_IF));
}

static void pzx_i2c_done(PzxI2CState *s)
{
    s->sr |= SR_IF;
    pzx_i2c_update_irq(s);
}

static void pzx_i2c_do_start(PzxI2CState *s)
{
    bool is_recv = s->cr & CR_DIR;
    int ret = i2c_start_transfer(s->bus, s->addr &0x7f, is_recv);

    if (ret != 0)
    {
        s->sr |= SR_RXAK;
        s->sr &= ~SR_BUSY;
        i2c_end_transfer(s->bus);
    }
    else
    {
        s->sr &= ~SR_RXAK;
        s->sr |= SR_BUSY;
    }
    pzx_i2c_done(s);
}

static void pzx_i2c_do_stop(PzxI2CState *s)
{
    if (s->sr & SR_BUSY)
    {
        i2c_end_transfer(s->bus);
        s->sr &= ~SR_BUSY;
    }
    pzx_i2c_done(s);
}

static uint64_t pzx_i2c_read(void *opaque, hwaddr addr, unsigned size)
{
    PzxI2CState *s = opaque;
    uint64_t ret = 0;
    switch (addr)
    {
        case PZX_I2C_CR:
            ret = s->cr;
            break;
        case PZX_I2C_SR:
            ret = s->sr;
            break;
        case PZX_I2C_ADDR:
            ret = s->addr;
            break;
        case PZX_I2C_DR:
            if ((s->cr & CR_EN) && (s->sr & SR_BUSY) && (s->cr & CR_DIR))
            {
                s->dr = i2c_recv(s->bus);
            }
            ret = s->dr;
            break;
        case PZX_I2C_CLKDIV:
            ret = s->clkdiv;
            break;
        default:
            break;
    }
    return ret;
}

static void pzx_i2c_write(void *opaque, hwaddr addr, uint64_t value, unsigned size)
{
    PzxI2CState *s = opaque;
    uint32_t val = value;
    uint32_t old = 0;

    switch (addr)
    {
        case PZX_I2C_CR:
            old = s->cr;
            s->cr = val;
            if ((val & CR_EN) && !(old & CR_EN))
            {
                s->sr &= ~(SR_BUSY | SR_RXAK);
            }
            if (!(val & CR_EN) && (old & CR_EN) && (s->sr & SR_BUSY))
            {
                i2c_end_transfer(s->bus);
                s->sr &= ~SR_BUSY;
            }
            if ((val & CR_EN) && (val & CR_START))
            {
                pzx_i2c_do_start(s);
            }
            if ((val & CR_EN) && (val & CR_STOP))
            {
                pzx_i2c_do_stop(s);
            }
            if ((val & CR_EN) && (val & CR_NACK) && (s->sr & SR_BUSY))
            {
                i2c_nack(s->bus);
            }
            s->cr &= ~(CR_START | CR_STOP | CR_NACK);
            pzx_i2c_update_irq(s);
            break;
        case PZX_I2C_SR:
            if (val & SR_IF)
            {
                s->sr &= ~SR_IF;
            }
            if (val & SR_RXAK)
            {
                s->sr &= ~SR_RXAK;
            }
            pzx_i2c_update_irq(s);
            break;
        case PZX_I2C_ADDR:
            s->addr = val & 0x7f;
            break;
        case PZX_I2C_DR:
            if ((s->cr & CR_EN) && (s->sr & SR_BUSY) && !(s->cr & CR_DIR))
            {
                s->dr = val & 0xff;
                if (i2c_send(s->bus, s->dr) != 0)
                {
                    s->sr |= SR_RXAK;
                    i2c_end_transfer(s->bus);
                    s->sr &= ~SR_BUSY;
                }
                else
                {
                    s->sr &= ~SR_RXAK;
                }
                pzx_i2c_done(s);
            }
        default:
            break;
    }
}

static void pzx_i2c_reset(DeviceState *dev)
{
    PzxI2CState *s = PZX_I2C(dev);
    s->cr = 0;
    s->sr = 0;
    s->addr = 0;
    s->dr = 0;
    s->clkdiv = 0;
}

static const MemoryRegionOps pzx_i2c_ops = {
    .read = pzx_i2c_read,
    .write = pzx_i2c_write,
    .endianness = DEVICE_LITTLE_ENDIAN,
    .valid = { .min_access_size = 4, .max_access_size = 4 },
};

static const VMStateDescription pzx_i2c_vmstate = {
    .name = TYPE_PZX_I2C,
    .version_id = 1,
    .minimum_version_id = 1,
    .fields = (const VMStateField[]) {
        VMSTATE_UINT32(cr, PzxI2CState),
        VMSTATE_UINT32(sr, PzxI2CState),
        VMSTATE_UINT32(addr, PzxI2CState),
        VMSTATE_UINT32(dr, PzxI2CState),
        VMSTATE_UINT32(clkdiv, PzxI2CState),
        VMSTATE_END_OF_LIST(),
    },
};

static void pzx_i2c_realize(DeviceState *dev, Error **errp)
{
    PzxI2CState *s = PZX_I2C(dev);
    sysbus_init_irq(SYS_BUS_DEVICE(dev), &s->irq);
    memory_region_init_io(&s->iomem, OBJECT(s), &pzx_i2c_ops,
        s, "pzx-i2c", PZX_I2C_MMIOSIZE);
    sysbus_init_mmio(SYS_BUS_DEVICE(dev), &s->iomem);
    s->bus = i2c_init_bus(dev, "i2c");
}

static void pzx_i2c_class_init(ObjectClass *oc, const void *data)
{
    DeviceClass *dc = DEVICE_CLASS(oc);

    dc->realize = pzx_i2c_realize;
    dc->vmsd = &pzx_i2c_vmstate;
    device_class_set_legacy_reset(dc, pzx_i2c_reset);
    dc->desc = "pzx custom i2c master";
}

// qemu gpio button code
static void pzx_btn_release_cb(void *opaque)
{
    PzxMachineState *state = opaque;

    pzxdebug("[time out: mask=%u, pressed=%u]\n", state->btn.pressed, state->btn.pressed);
    if (state->btn.pressed == 0)
    {
        return ;
    }

    state->btn.pressed = 0;
    for (int i = 0; i < BTN_MAX; i++)
    {
        qemu_set_irq(state->btn.gpio[i], 1);
    }
}

static void pzx_set_btn_press_ms(Object *obj, const char *val, Error **errp)
{
    //val format: mask@duration
    PzxMachineState *state = PZX_MACHINE(obj);
    unsigned int mask;
    unsigned int duration;

    if (state->btn.pressed || !state->btn.timer)
    {
        error_setg(errp, "pzx: is pressing or timer is not initialized");
        return ;
    }

    if (val == NULL)
    {
        error_setg(errp, "pzx: invalid command");
        return ;
    }

    int ret = sscanf(val, "%u@%u", &mask, &duration);
    if (ret != 2 || duration < 10 || duration > 10000)
    {
        error_setg(errp, "pzx: invalid command");
        return ;
    }

    pzxdebug("[btn press: mask=%u, duration=%u]\n", mask, duration);
    timer_del(state->btn.timer);
    state->btn.pressed = mask;
    for (int i = 0; i < BTN_MAX; i++)
    {
        int level = (mask & (1 << i)) ? 0x0 : 0x1;
        pzxdebug("[btn press: btn=%d, level=%d]\n", i, level);
        qemu_set_irq(state->btn.gpio[i], level);
    }
    timer_mod(state->btn.timer, qemu_clock_get_ms(QEMU_CLOCK_REALTIME) + duration);
}

// board code
static void pzx_machine_init(MachineState *machine)
{
    PzxMachineState *state = PZX_MACHINE(machine);
    MemoryRegion *sysmem = get_system_memory();
    int i = 0;

    while (i < MAX_CPUS)
    {
        Object *cpuobj = object_new(ARM_CPU_TYPE_NAME("cortex-a53"));
        object_property_set_int(cpuobj, "mp-affinity", i, &error_fatal);
        CPU(cpuobj)->cpu_index = i;
        state->cpu[i] = ARM_CPU(cpuobj);
        qdev_realize(DEVICE(state->cpu[i]), NULL, &error_fatal);
        i++;
    }

    memory_region_init_rom(&state->mrom, NULL, "pzx.mrom",
            pzx_memmap[ID_MROM].size, &error_fatal);
    memory_region_add_subregion(sysmem, pzx_memmap[ID_MROM].base, &state->mrom);

    memory_region_init_ram(&state->sram, NULL, "pzx.sram",
            pzx_memmap[ID_SRAM].size, &error_fatal);
    memory_region_add_subregion(sysmem, pzx_memmap[ID_SRAM].base, &state->sram);

    memory_region_init_ram(&state->dram, NULL, "pzx.dram",
            pzx_memmap[ID_DRAM].size, &error_fatal);
    memory_region_add_subregion(sysmem, pzx_memmap[ID_DRAM].base, &state->dram);

    state->gic = qdev_new(TYPE_ARM_GICV3);
    uint32_t redist0_capacity = pzx_memmap[ID_GIC_REDIST].size / GICV3_REDIST_SIZE;
    uint32_t redist0_count = MIN(machine->smp.cpus, redist0_capacity);
    QList *redist_list = qlist_new();
    qlist_append_int(redist_list, redist0_count);
    qdev_prop_set_uint32(state->gic, "revision", 3);
    qdev_prop_set_uint32(state->gic, "num-cpu", machine->smp.cpus);
    qdev_prop_set_uint32(state->gic, "num-irq", 32 + 64);
    qdev_prop_set_array(state->gic, "redist-region-count", redist_list);
    sysbus_realize_and_unref(SYS_BUS_DEVICE(state->gic), &error_fatal);
    sysbus_mmio_map(SYS_BUS_DEVICE(state->gic), 0, pzx_memmap[ID_GIC_DIST].base);
    sysbus_mmio_map(SYS_BUS_DEVICE(state->gic), 1, pzx_memmap[ID_GIC_REDIST].base);

    // connect cpu to gic
    const int timer_irq[] = {
        [GTIMER_PHYS] = ARCH_TIMER_NS_EL1_IRQ,
        [GTIMER_VIRT] = ARCH_TIMER_VIRT_IRQ,
        [GTIMER_HYP]  = ARCH_TIMER_NS_EL2_IRQ,
        [GTIMER_SEC]  = ARCH_TIMER_S_EL1_IRQ,
        [GTIMER_HYPVIRT] = ARCH_TIMER_NS_EL2_VIRT_IRQ,
        [GTIMER_S_EL2_PHYS] = ARCH_TIMER_S_EL2_IRQ,
        [GTIMER_S_EL2_VIRT] = ARCH_TIMER_S_EL2_VIRT_IRQ,
    };

    for (i = 0; i < MAX_CPUS; i++)
    {
        DeviceState *cpudev = DEVICE(state->cpu[i]);
        int ppi_base = 64 + i * 32;
        for (unsigned irq = 0; irq < ARRAY_SIZE(timer_irq); irq++)
        {
            qdev_connect_gpio_out(cpudev, irq, qdev_get_gpio_in(state->gic, ppi_base + timer_irq[irq]));
        }
        sysbus_connect_irq(SYS_BUS_DEVICE(state->gic), i + 0 * MAX_CPUS, qdev_get_gpio_in(cpudev, ARM_CPU_IRQ));
        sysbus_connect_irq(SYS_BUS_DEVICE(state->gic), i + 1 * MAX_CPUS, qdev_get_gpio_in(cpudev, ARM_CPU_FIQ));
        sysbus_connect_irq(SYS_BUS_DEVICE(state->gic), i + 2 * MAX_CPUS, qdev_get_gpio_in(cpudev, ARM_CPU_VIRQ));
        sysbus_connect_irq(SYS_BUS_DEVICE(state->gic), i + 3 * MAX_CPUS, qdev_get_gpio_in(cpudev, ARM_CPU_VFIQ));
    }

    DeviceState *pl011 = qdev_new(TYPE_PL011);
    qdev_prop_set_chr(pl011, "chardev", serial_hd(0));
    sysbus_realize_and_unref(SYS_BUS_DEVICE(pl011), &error_fatal);
    sysbus_mmio_map(SYS_BUS_DEVICE(pl011), 0, pzx_memmap[ID_UART].base);
    sysbus_connect_irq(SYS_BUS_DEVICE(pl011), 0, qdev_get_gpio_in(state->gic, IRQ_UART));

    DeviceState *sdhost = qdev_new("pl181");
    sysbus_realize_and_unref(SYS_BUS_DEVICE(sdhost), &error_fatal);
    sysbus_mmio_map(SYS_BUS_DEVICE(sdhost), 0, pzx_memmap[ID_SD].base);
    sysbus_connect_irq(SYS_BUS_DEVICE(sdhost), 0, qdev_get_gpio_in(state->gic, IRQ_SD));
    DriveInfo *drvinfo = drive_get(IF_SD, 0, 0);
    if (drvinfo)
    {
        DeviceState *sdcard = qdev_new(TYPE_SD_CARD);
        qdev_prop_set_drive_err(sdcard, "drive", blk_by_legacy_dinfo(drvinfo), &error_fatal);
        qdev_realize_and_unref(sdcard, qdev_get_child_bus(sdhost, "sd-bus"), &error_fatal);
    }

    DeviceState *sysctl = qdev_new(TYPE_PZX_SYSCTL);
    sysbus_realize_and_unref(SYS_BUS_DEVICE(sysctl), &error_fatal);
    sysbus_mmio_map(SYS_BUS_DEVICE(sysctl), 0, pzx_memmap[ID_SYSCTL].base);

    DeviceState *net_dev = qdev_new("virtio-mmio");
    sysbus_realize_and_unref(SYS_BUS_DEVICE(net_dev), &error_fatal);
    sysbus_mmio_map(SYS_BUS_DEVICE(net_dev), 0, pzx_memmap[ID_VIRTIO_NET].base);
    sysbus_connect_irq(SYS_BUS_DEVICE(net_dev), 0, qdev_get_gpio_in(state->gic, IRQ_VIRTIO_NET));

    DeviceState *gpio = qdev_new("pl061");
    qdev_prop_set_uint32(gpio, "pullups", 0xff);
    qdev_prop_set_uint32(gpio, "pulldowns", 0x00);
    sysbus_realize_and_unref(SYS_BUS_DEVICE(gpio), &error_fatal);
    sysbus_mmio_map(SYS_BUS_DEVICE(gpio), 0, pzx_memmap[ID_GPIO].base);
    sysbus_connect_irq(SYS_BUS_DEVICE(gpio), 0, qdev_get_gpio_in(state->gic, IRQ_GPIO));

    DeviceState *i2c = qdev_new(TYPE_PZX_I2C);
    sysbus_realize_and_unref(SYS_BUS_DEVICE(i2c), &error_fatal);
    sysbus_mmio_map(SYS_BUS_DEVICE(i2c), 0, pzx_memmap[ID_I2C].base);
    sysbus_connect_irq(SYS_BUS_DEVICE(i2c), 0, qdev_get_gpio_in(state->gic, IRQ_I2C));
    //I2CBus *bus = I2C_BUS(qdev_get_child_bus(i2c, "i2c"));

    // set debug code gpio button
    for (i = 0; i < BTN_MAX; i++)
    {
        state->btn.gpio[i] = qdev_get_gpio_in(gpio, i);
        qemu_set_irq(state->btn.gpio[i], 1);
    }
    state->btn.timer = timer_new_ms(QEMU_CLOCK_REALTIME, pzx_btn_release_cb, state);
    state->btn.pressed = 0;

    rom_add_blob_fixed("bootcode", bootcode, bootcode_size, pzx_memmap[ID_MROM].base);
}

static void pzx_machine_finalize(Object *obj)
{
    PzxMachineState *state = PZX_MACHINE(obj);

    if (state->btn.timer)
    {
        timer_del(state->btn.timer);
        timer_free(state->btn.timer);
        state->btn.timer = NULL;
    }
}

static void pzx_machine_class_init(ObjectClass *oc, const void *data)
{
    MachineClass *mc = MACHINE_CLASS(oc);

    mc->desc = "pzx.arm64.machine";
    mc->init = pzx_machine_init;

// debug code
    object_class_property_add_str(oc, "btn_press", NULL, pzx_set_btn_press_ms);
}

